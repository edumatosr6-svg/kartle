#!/usr/bin/env python3
"""The deterministic gate: everything about a stage's artifacts that a script can decide.

Run by every loop BEFORE its model validator. The validator never re-judges what this settles
(pipeline-conventions §13) - a model pass spent on findings a script produces for free is the most
expensive habit a loop can have, and the script produces them deterministically.

    python .claude/skills/pipeline-progress/scripts/lint_artifacts.py --stage req --feature account-timeline
    python .claude/skills/pipeline-progress/scripts/lint_artifacts.py --stage req --feature account-timeline --emit
    python .claude/skills/pipeline-progress/scripts/lint_artifacts.py --stage fspec --feature account-timeline --json

Exit code: 0 when no error, 1 when any error, 2 when the stage folder is absent.

`--emit` regenerates the DERIVED files - `00-index.md` and `99-traceability.md` - from the artifacts
themselves, and is the only thing that ever writes them (conventions §13). A generator that hand-writes
a derived file reintroduces the largest class of finding in the pipeline: one fact in four places, one
of them stale.

Stdlib only. Without `--emit` it writes nothing.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

# --------------------------------------------------------------------------- stage tables

# (key -> output root). Not uniform: `200 Requirements` numbers its sides. Stated literally,
# never derived by pattern (conventions §2).
STAGES: dict[str, str] = {
    "req": "200 Requirements/230 Output",
    "fspec": "300 Specs/320 F-Specs/Output",
    "dspec": "300 Specs/330 D-Specs/Output",
    "code": "400 Code/Output",
    "test": "500 Tests/Output",
    "deploy": "600 Deploy/Output",
}
# The id prefixes each stage may define, per conventions §4.
PREFIXES: dict[str, list[str]] = {
    "req": ["US", "NFR"],
    "fspec": ["FEAT", "FLOW", "API", "SCR", "RULE"],
    "dspec": ["DES", "DM", "ADR"],
    "code": ["DES", "DM"],
    "test": ["TEST"],
    "deploy": ["REL"],
}
# Child ids defined inside a file, keyed to their parent's id: (child prefix, pattern).
CHILD: dict[str, tuple[str, re.Pattern[str]]] = {
    "req": ("AC", re.compile(r"\bAC-(US-\d{4})-(\d{2})\b")),
    "fspec": ("REQ", re.compile(r"\bREQ-(FEAT-\d{4})-(\d{2})\b")),
    "test": ("CHK", re.compile(r"\bCHK-(TEST-\d{4})-(\d{2})\b")),
}
# A file of these prefixes must define at least one child id - a story with no criterion,
# a feature spec with no requirement or a test spec with no check is not usable downstream.
NEEDS_CHILD: dict[str, str] = {"req": "US", "fspec": "FEAT", "test": "TEST"}

# Files every stage must carry. Mirrors pipeline_progress.REQUIRED, plus the changelog (§18).
REQUIRED: dict[str, list[str]] = {
    "req": ["00-index.md", "01-context.md", "02-glossary.md", "97-changelog.md", "99-traceability.md"],
    "fspec": ["00-index.md", "01-overview.md", "02-glossary.md", "97-changelog.md", "99-traceability.md"],
    "dspec": ["00-index.md", "01-architecture.md", "test-strategy.md", "97-changelog.md", "99-traceability.md"],
    "code": ["00-index.md", "97-changelog.md", "99-traceability.md"],
    "test": ["00-index.md", "97-changelog.md", "99-traceability.md"],
    "deploy": ["00-index.md", "01-release.md", "runbook.md", "smoke.md", "97-changelog.md"],
}
# Generated by --emit; never hand-written, never linted for prose.
DERIVED = {"00-index.md", "99-traceability.md"}
# PROSE files: context, glossary, changelog, divergences, architecture, runbook and the like.
# They carry front matter, but no id of their own and no child ids - they state, they do not specify.
# Everything else is an ID-BEARING artifact and is held to G3/G4.
PROSE = re.compile(r"^(\d{2}-|test-strategy|runbook|smoke)")

FM_RE = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.DOTALL)
KV_RE = re.compile(r"^([A-Za-z_][A-Za-z0-9_-]*)\s*:\s*(.*)$")
ID_RE = re.compile(r"^([A-Z]{2,4})-(\d{4})$")
OPEN_RE = re.compile(r"\bOPEN-\d{1,3}\b")
TBD_RE = re.compile(r"\bTBD\b|\bTO ?DO\b")
SEMVER_RE = re.compile(r"^\d+\.\d+(\.\d+)?$")
STATUS = {"draft", "validated"}


# --------------------------------------------------------------------------- model

@dataclass
class Finding:
    severity: str
    check: str
    file: str
    finding: str

    def line(self) -> str:
        return f"{self.severity}: [{self.check}] {self.file}: {self.finding}"


@dataclass
class Artifact:
    path: Path
    rel: str
    fm: dict[str, str]
    body: str
    children: list[str] = field(default_factory=list)

    @property
    def id(self) -> str:
        return self.fm.get("id", "")


def read_fm(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8", errors="replace")
    m = FM_RE.match(text)
    if not m:
        return {}, text
    fm: dict[str, str] = {}
    for line in m.group(1).splitlines():
        kv = KV_RE.match(line.strip())
        if kv:
            fm[kv.group(1)] = kv.group(2).strip()
    return fm, text[m.end():]


def parse_list(value: str) -> list[str]:
    value = value.strip()
    if value.startswith("[") and value.endswith("]"):
        value = value[1:-1]
    return [v.strip().strip("'\"") for v in value.split(",") if v.strip()]


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


# --------------------------------------------------------------------------- the gate

def collect(out: Path) -> list[Artifact]:
    arts = []
    for p in sorted(out.rglob("*.md")):
        if "reports" in p.relative_to(out).parts:
            continue
        rel = p.relative_to(out).as_posix()
        if rel in DERIVED:
            continue
        fm, body = read_fm(p)
        arts.append(Artifact(p, rel, fm, body))
    return arts


def lint(root: Path, stage: str, feature: str, allow_open: bool) -> tuple[list[Finding], list[Artifact], Path]:
    out = root / STAGES[stage] / feature
    found: list[Finding] = []

    def err(check, file, msg): found.append(Finding("error", check, file, msg))
    def warn(check, file, msg): found.append(Finding("warning", check, file, msg))

    arts = collect(out)

    # G1 - the set is present and complete
    for name in REQUIRED[stage]:
        if not (out / name).is_file():
            err("G1", name, "required file is missing")
    if not arts:
        err("G1", ".", "no artifact file found besides the derived ones")

    child_prefix, child_re = CHILD.get(stage, ("", None))
    ids: dict[str, str] = {}
    all_children: dict[str, str] = {}

    for a in arts:
        is_prose = bool(PROSE.match(Path(a.rel).name))

        # G2 - front matter
        if not a.fm:
            err("G2", a.rel, "no YAML front matter")
            continue
        keys = ("title", "feature", "stage", "status", "version")
        for key in (keys if is_prose else ("id",) + keys):
            if key not in a.fm:
                err("G2", a.rel, f"front matter lacks `{key}`")
        if a.fm.get("feature") and a.fm["feature"] != feature:
            err("G2", a.rel, f"`feature: {a.fm['feature']}` is not `{feature}`")
        if a.fm.get("stage") and a.fm["stage"] != stage:
            err("G2", a.rel, f"`stage: {a.fm['stage']}` is not `{stage}`")
        if a.fm.get("status") and a.fm["status"] not in STATUS:
            err("G2", a.rel, f"`status: {a.fm['status']}` is not draft | validated")
        if a.fm.get("version") and not SEMVER_RE.match(a.fm["version"]):
            err("G2", a.rel, f"`version: {a.fm['version']}` is not a semver")

        # G3 - ids: format, agreement with the filename, uniqueness
        fid = a.id
        if fid and not is_prose:
            m = ID_RE.match(fid)
            if not m:
                err("G3", a.rel, f"id `{fid}` is not <PREFIX>-<nnnn>")
            else:
                if m.group(1) not in PREFIXES[stage]:
                    err("G3", a.rel, f"id prefix `{m.group(1)}` is not one of {PREFIXES[stage]} for stage {stage}")
                if not Path(a.rel).name.startswith(fid):
                    err("G3", a.rel, f"filename does not start with its id `{fid}`")
                if fid in ids:
                    err("G3", a.rel, f"id `{fid}` already used by {ids[fid]}")
                else:
                    ids[fid] = a.rel

        # G4 - child ids
        if child_re and not is_prose:
            for parent, num in child_re.findall(a.body):
                cid = f"{child_prefix}-{parent}-{num}"
                a.children.append(cid)
                if fid and parent != fid:
                    err("G4", a.rel, f"{cid} is a child of {parent}, but this file is {fid}")
                if cid in all_children:
                    err("G4", a.rel, f"child id {cid} already defined in {all_children[cid]}")
                else:
                    all_children[cid] = a.rel
            need = NEEDS_CHILD.get(stage)
            if need and fid.startswith(need + "-") and not a.children:
                err("G4", a.rel, f"{fid} defines no child id — nothing downstream can verify it")

        # G5 - openness
        if TBD_RE.search(a.body):
            err("G5", a.rel, "`TBD`/`TODO` marker present — make it an OPEN-<nn> or resolve it")
        if not allow_open:
            for oid in sorted(set(OPEN_RE.findall(a.body))):
                err("G5", a.rel, f"{oid} unresolved — this stage does not carry open items forward")

    # G6 - sources resolve upward. Stage req is exempt: its upstream is the seed, whose items carry
    # no id scheme of their own (conventions §4 starts at US-/NFR-).
    if stage != "req":
        for a in arts:
            if PROSE.match(Path(a.rel).name):
                continue
            for src in parse_list(a.fm.get("sources", "")):
                if not re.match(r"^[A-Z]{2,4}-(?:[A-Z]{2,4}-)?\d{4}(?:-\d{2})?$", src):
                    warn("G6", a.rel, f"`sources:` entry `{src}` is not an upstream id")

    # G7 - the index agrees with the folder
    index = out / "00-index.md"
    if index.is_file():
        listed = set(re.findall(r"`([^`]+\.md)`", index.read_text(encoding="utf-8", errors="replace")))
        present = {a.rel for a in arts}
        for missing in sorted(present - listed):
            err("G7", "00-index.md", f"{missing} exists but is not listed — re-run with --emit")
        for ghost in sorted(listed - present - DERIVED - set(REQUIRED[stage])):
            err("G7", "00-index.md", f"{ghost} is listed but does not exist — re-run with --emit")

    # G8 - traceability resolves
    trace = out / "99-traceability.md"
    if trace.is_file():
        known = set(ids) | set(all_children)
        owned = set(PREFIXES[stage]) | ({child_prefix} if child_prefix else set())
        for ref in sorted(set(re.findall(r"\b([A-Z]{2,4}-(?:[A-Z]{2,4}-)?\d{4}(?:-\d{2})?)\b",
                                         trace.read_text(encoding="utf-8", errors="replace")))):
            if ref.split("-")[0] in owned and ref not in known:
                err("G8", "99-traceability.md",
                    f"{ref} is referenced but defined in no artifact of this stage — re-run with --emit")

    return found, arts, out


# --------------------------------------------------------------------------- emit

def emit(root: Path, stage: str, feature: str, arts: list[Artifact], out: Path) -> list[str]:
    written = []

    lines = ["---", f"stage: {stage}", f"feature: {feature}",
             f"status: {'validated' if all(a.fm.get('status') == 'validated' for a in arts) and arts else 'draft'}"]
    lines += [f"generated: {utc_now()}", "files: %d" % len(arts), "---", "",
              "# Index", "",
              "<!-- GENERATED by lint_artifacts.py --emit. Do not edit: your edit will be overwritten. -->", "",
              "| File | Id | Title | Status | Version |", "|---|---|---|---|---|"]
    for a in sorted(arts, key=lambda x: x.rel):
        lines.append(f"| `{a.rel}` | {a.id or '-'} | {a.fm.get('title', '-')} | "
                     f"{a.fm.get('status', '-')} | {a.fm.get('version', '-')} |")
    (out / "00-index.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    written.append("00-index.md")

    if "99-traceability.md" in REQUIRED[stage]:
        rows: list[tuple[str, str, str, str]] = []
        specs = [a for a in arts if not PROSE.match(Path(a.rel).name)]
        for a in sorted(specs, key=lambda x: x.rel):
            srcs = parse_list(a.fm.get("sources", "")) or ["-"]
            for src in srcs:
                rows.append((src, a.id or "-", ", ".join(a.children) or "-", a.rel))
        t = ["---", f"stage: {stage}", f"feature: {feature}", f"generated: {utc_now()}",
             f"rows: {len(rows)}", "---", "", "# Traceability", "",
             "<!-- GENERATED by lint_artifacts.py --emit. Do not edit: your edit will be overwritten. -->", "",
             "Upstream item -> this stage's item -> the ids that make it verifiable.", "",
             "| Upstream | This stage | Verifiable by | File |", "|---|---|---|---|"]
        for src, aid, kids, rel in sorted(rows):
            t.append(f"| {src} | {aid} | {kids} | `{rel}` |")
        orphans = [a.id for a in specs if a.id and not parse_list(a.fm.get("sources", ""))]
        t += ["", "## Items with no upstream source", ""]
        t.append(", ".join(sorted(orphans)) if orphans else "None.")
        (out / "99-traceability.md").write_text("\n".join(t) + "\n", encoding="utf-8")
        written.append("99-traceability.md")

    return written


# --------------------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--stage", required=True, choices=sorted(STAGES))
    ap.add_argument("--feature", required=True)
    ap.add_argument("--root", default=".")
    ap.add_argument("--emit", action="store_true",
                    help="regenerate 00-index.md and 99-traceability.md from the artifacts")
    ap.add_argument("--allow-open", action="store_true",
                    help="do not fail on an unresolved OPEN-<nn> (a stage that deliberately carries them)")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()

    root = Path(a.root).resolve()
    out = root / STAGES[a.stage] / a.feature
    if not out.is_dir():
        print(f"no stage output at {out.relative_to(root)} — nothing to lint", file=sys.stderr)
        return 2

    findings, arts, out = lint(root, a.stage, a.feature, a.allow_open)

    written: list[str] = []
    if a.emit:
        written = emit(root, a.stage, a.feature, arts, out)
        findings = [f for f in lint(root, a.stage, a.feature, a.allow_open)[0]]

    n_err = sum(1 for f in findings if f.severity == "error")
    n_warn = len(findings) - n_err

    if a.json:
        print(json.dumps({"stage": a.stage, "feature": a.feature, "files": len(arts),
                          "errors": n_err, "warnings": n_warn, "emitted": written,
                          "findings": [f.__dict__ for f in findings]}, ensure_ascii=False, indent=2))
    else:
        for f in findings:
            print(f.line())
        if written:
            print(f"\nemitted: {', '.join(written)}")
        print(f"\ngate: {n_err} error(s), {n_warn} warning(s) over {len(arts)} file(s) "
              f"of {a.feature} at stage {a.stage}")
        if not arts:
            print("NOTE: a gate that examined no file is not a pass (conventions §13).")

    return 1 if n_err else 0


if __name__ == "__main__":
    sys.exit(main())
